import { makeGrid, gate, rect, wire, hWire, vWire } from "./util";
import type { Grid2D } from "../core/types";

const NOT = 6;
const SWITCH = 11;
const BULB = 9;

// Ячейка SRAM: два инвертора, включённые в кольцо.
//
// В реальной схеме кольцо из двух инверторов — это НЕ генератор, а
// бистабильный элемент (так устроена ячейка статической памяти): у него два
// устойчивых состояния, и он ДЕРЖИТ бит. Генератором становится кольцо с
// нечётным числом инверторов (см. demo ringOsc).
//
// Поэтому здесь кольцо ведёт себя как настоящая ячейка памяти:
//   * при включении питания состояние выбирается одно из двух (в реальной
//     схеме — случайно из-за шума, здесь — детерминированно);
//   * переключатель SET подтягивает узел Q к 1 — ячейка записывает 1;
//   * переключатель RESET подтягивает узел nQ к 1 — ячейка сбрасывается в 0;
//   * между нажатиями ячейка хранит последний записанный бит.
//
// Сеть = связная область провода, поэтому все провода одного цвета, а разные
// сети разведены зазором: Q идёт по прямой между инверторами, nQ — обходом
// снизу.
export function sramCell(): Grid2D {
  const g = makeGrid(20, 12);

  gate(g, 5, 3, NOT); // NOT1 x5-7 y3-5: W(5,4) — вход, E(7,4) — выход
  gate(g, 13, 3, NOT); // NOT2 x13-15 y3-5: W(13,4) — вход, E(15,4) — выход

  // сеть Q: NOT1.E(7,4) -> NOT2.W(13,4), плюс ответвление к SET и лампочке
  hWire(g, 8, 12, 4);

  // сеть nQ: NOT2.E(15,4) -> вниз по x=16 -> низом налево -> вверх -> NOT1.W(5,4)
  wire(g, 16, 4);
  vWire(g, 16, 4, 9);
  hWire(g, 2, 16, 9);
  vWire(g, 2, 4, 9);
  hWire(g, 2, 4, 4);

  // SET: подтягивает Q к 1 (выход переключателя — на юге)
  rect(g, 8, 1, SWITCH, 2, 2); // SWITCH x8-9 y1-2, выход на юге (8,3),(9,3)
  wire(g, 9, 3); // -> в сеть Q (9,4)

  // RESET: подтягивает nQ к 1
  rect(g, 6, 7, SWITCH, 2, 2); // SWITCH x6-7 y7-8, выход на юге (6,9),(7,9)
  // -> сеть nQ: шина y9 уже проходит через эти клетки

  // лампочка показывает записанный бит Q (вход лампочки — на севере)
  rect(g, 9, 5, BULB, 2, 2); // BULB x9-10 y5-6, N=(9,4),(10,4) — сеть Q

  return g;
}
