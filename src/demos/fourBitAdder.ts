import { makeGrid, gate, rect, hWire, vWire, bridge, segDigit } from "./util";
import type { Grid2D } from "../core/types";

const AND = 3;
const OR = 4;
const XOR = 5;
const BULB = 9;
const SWITCH = 11;

// 4-битный сумматор с последовательным переносом (ripple-carry).
//
// Каждый бит — это полный сумматор:
//   X   = A XOR B
//   S   = X XOR Cin
//   Cout= (A AND B) OR (Cin AND X)
// Т.е. пять гейтов на разряд (XOR, AND, XOR, AND, OR). Разряды выложены
// слева направо (LSB слева, порядок A0..A3 / B0..B3), перенос идёт по нижнему
// каналу (строка BY+34) в следующий разряд. Разряд 0 без входного переноса:
// его сеть Cin остаётся без драйвера и читается как 0 (инвариант «сеть без
// драйвера = 0»).
//
// Входы сгруппированы. Переключатели стоят двумя рядами над разрядами:
// верхний ряд — A0..A3, ниже через широкий зазор — B0..B3 (клик в run-режиме
// переключает бит). Каждый переключатель стоит над своим разрядом и опускает
// провод к его входам, поэтому шины входов не пересекаются.
//
// Выходы сгруппированы в нижний ряд лампочек: S0..S3 и правее всех — лампочка
// переноса старшего разряда.
//
// Визуальные подсказки (текста в PNG нет):
//   • один вертикальный «лейн» на бит — A_i/B_i сверху, вентили в середине,
//     S_i снизу в той же полосе; между полосами широкий пустой гуттер;
//   • вес бита: слева от свитчей каждого бита нарисована цифра 1/2/4/8
//     проводом в стиле семисегментного индикатора (util.segDigit). Это
//     отдельный висячий провод (ни к чему не подключён → читается как 0,
//     на логику не влияет);
//   • порядок LSB→MSB слева направо; перенос внизу течёт слева направо.
//
// Все пересечения разных сетей сделаны МОСТАМИ «плюс без центровины»
// (util.bridge): центр пустой, четыре рукава — провода, парсер читает
// горизонталь и вертикаль как две независимые сети (см. AGENTS.md, инв. 2).

const BASE_X = 12;
const PITCH = 84; // контент разряда 64 клетки + гуттер между лейнами
const BY = 16; // вертикальный отступ разряда: над ним ряды переключателей
const BULB_Y = 56; // нижний ряд лампочек (суммы + перенос)
const A_ROW = 2; // верхний ряд свитчей (число A)
const B_ROW = 11; // нижний ряд свитчей (число B), через зазор

// Один разряд. `bx` — левый край контента; свитчи стоят выше, в зазоре слева
// (bx-5..bx-2), цифра веса — ещё левее (bx-11..bx-9).
function drawBit(g: Grid2D, bx: number, bit: number): void {
  // ── вес бита: цифра 2^bit (1/2/4/8), нарисованная проводом ──────────────
  segDigit(g, bx - 11, A_ROW, String(1 << bit));

  // ── входы: переключатели A и B разряда в общих верхних рядах ─────────────
  rect(g, bx - 3, A_ROW, SWITCH, 2, 2); // A: выход вниз, (bx-2,A_ROW+2)
  vWire(g, bx - 2, A_ROW + 2, BY + 4);
  hWire(g, bx - 2, bx, BY + 4); // -> ввод A (строка BY+4)
  rect(g, bx - 5, B_ROW, SWITCH, 2, 2); // B: выход вниз, (bx-5,B_ROW+2)
  vWire(g, bx - 5, B_ROW + 2, BY + 8);
  hWire(g, bx - 5, bx, BY + 8); // -> ввод B (строка BY+8)

  // ── тела вентилей (rot=0: входы на W, выход на E) ───────────────────────
  gate(g, bx + 10, BY + 4, XOR); // XOR1  X   = A^B
  gate(g, bx + 10, BY + 14, AND); // AND1  AB  = A&B
  gate(g, bx + 30, BY + 4, XOR); // XOR2  S   = X^Cin
  gate(g, bx + 30, BY + 14, AND); // AND2  CX  = Cin&X
  gate(g, bx + 46, BY + 14, OR); // OR1   Cout= AB|CX

  // ── сеть A: ввод + ствол + питание XOR1/AND1 ────────────────────────────
  hWire(g, bx, bx + 9, BY + 4);
  vWire(g, bx + 3, BY + 4, BY + 14);
  hWire(g, bx + 3, bx + 9, BY + 14);

  // ── сеть B: ввод + ствол + питание XOR1/AND1 ────────────────────────────
  hWire(g, bx, bx + 5, BY + 8);
  vWire(g, bx + 5, BY + 6, BY + 16);
  hWire(g, bx + 5, bx + 9, BY + 6);
  hWire(g, bx + 5, bx + 9, BY + 16);

  // ── сеть X: выход XOR1 + ствол + питание XOR2/AND2 ──────────────────────
  hWire(g, bx + 13, bx + 19, BY + 5);
  vWire(g, bx + 19, BY + 5, BY + 9);
  hWire(g, bx + 19, bx + 24, BY + 9);
  vWire(g, bx + 24, BY + 4, BY + 14);
  hWire(g, bx + 24, bx + 29, BY + 4);
  hWire(g, bx + 24, bx + 29, BY + 14);

  // ── сеть Cin: ствол вниз к каналу переноса + питание XOR2/AND2 ──────────
  vWire(g, bx + 21, BY + 6, BY + 34);
  hWire(g, bx + 21, bx + 29, BY + 6);
  hWire(g, bx + 21, bx + 29, BY + 16);

  // ── сеть AB: выход AND1 вниз, вправо и к верхнему входу OR1 ─────────────
  hWire(g, bx + 13, bx + 14, BY + 15);
  vWire(g, bx + 14, BY + 15, BY + 24);
  hWire(g, bx + 14, bx + 38, BY + 24);
  vWire(g, bx + 38, BY + 14, BY + 24);
  hWire(g, bx + 38, bx + 45, BY + 14);

  // ── сеть CX: выход AND2 вниз и к нижнему входу OR1 ──────────────────────
  hWire(g, bx + 33, bx + 34, BY + 15);
  vWire(g, bx + 34, BY + 15, BY + 16);
  hWire(g, bx + 34, bx + 45, BY + 16);

  // ── выход суммы S: вниз к общей нижней лампочке разряда ─────────────────
  hWire(g, bx + 33, bx + 60, BY + 5);
  vWire(g, bx + 60, BY + 5, BULB_Y - 1);
  rect(g, bx + 59, BULB_Y, BULB, 3, 3); // N→(bx+60,BULB_Y)

  // ── выход переноса: вниз к каналу переноса ──────────────────────────────
  vWire(g, bx + 49, BY + 15, BY + 34);

  // ── мосты: все пересечения разных сетей без соединения ──────────────────
  bridge(g, bx + 3, BY + 8); // ствол A × ввод B
  bridge(g, bx + 5, BY + 14); // ствол B × питание A (AND1)
  bridge(g, bx + 21, BY + 9); // ствол Cin × выход X
  bridge(g, bx + 24, BY + 6); // ствол X × питание Cin (XOR2)
  bridge(g, bx + 21, BY + 24); // ствол Cin × ствол AB
  bridge(g, bx + 38, BY + 16); // ствол AB × выход CX
}

// 4-битный сумматор: A0..A3 + B0..B3 → S0..S3 + carry.
export function fourBitAdder(): Grid2D {
  const g = makeGrid(BASE_X + PITCH * 4 + 24, 62);

  for (let i = 0; i < 4; i++) {
    const bx = BASE_X + i * PITCH;
    drawBit(g, bx, i);
    const coutCol = bx + 49;
    if (i < 3) {
      // перенос в следующий разряд: вниз и по каналу до его ствола Cin
      const nextCinCol = bx + PITCH + 21;
      hWire(g, coutCol, nextCinCol, BY + 34);
      bridge(g, bx + 60, BY + 34); // сумма разряда пересекает канал переноса
    } else {
      // перенос старшего разряда — на общую нижнюю лампочку
      hWire(g, coutCol, bx + 68, BY + 34);
      bridge(g, bx + 60, BY + 34);
      vWire(g, bx + 68, BY + 34, BULB_Y - 1);
      rect(g, bx + 67, BULB_Y, BULB, 3, 3); // N→(bx+68,BULB_Y)
    }
  }

  return g;
}
