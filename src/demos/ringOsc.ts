import { makeGrid, gate, rect, wire, hWire, vWire } from "./util";
import type { Grid2D } from "../core/types";

const NOT = 6;
const BULB = 9;

// Кольцевой генератор: три инвертора в кольце.
//
// Настоящий кольцевой осциллятор — именно так он и устроен в реальных
// микросхемах: сигнал бежит по кольцу инверторов и, обойдя кольцо, меняет
// полярность. Ключевое условие: инверторов НЕЧЁТНОЕ число — тогда за полный
// обход сигнал меняет знак и кольцо самоподдерживает колебания. При чётном
// числе инверсий у кольца появляется устойчивое состояние, и оно превращается
// в ячейку памяти (см. demo sramCell).
//
// Период в модели: 2 × 3 инвертора × задержка 1 тик = 6 тиков, то есть волна
// действительно обходит кольцо, а не переключает все узлы разом. Стартовое
// состояние симметрично (все узлы нули) — в реальной схеме его ломает шум
// включения, здесь то же самое делает симулятор (см. core/sim.ts).
export function ringOsc(): Grid2D {
  const g = makeGrid(22, 12);

  gate(g, 3, 3, NOT); // NOT1 x3-5 y3-5: W(3,4) — вход, E(5,4) — выход
  gate(g, 9, 3, NOT); // NOT2 x9-11 y3-5: W(9,4) — вход, E(11,4) — выход
  gate(g, 15, 3, NOT); // NOT3 x15-17 y3-5: W(15,4) — вход, E(17,4) — выход

  // сеть a: NOT1.E(5,4) -> NOT2.W(9,4)
  hWire(g, 6, 8, 4);

  // сеть b: NOT2.E(11,4) -> NOT3.W(15,4)
  hWire(g, 12, 14, 4);

  // сеть c: NOT3.E(17,4) -> вниз по x=18 -> низом налево -> вверх -> NOT1.W(3,4)
  wire(g, 18, 4);
  vWire(g, 18, 4, 8);
  hWire(g, 2, 18, 8);
  vWire(g, 2, 4, 8);
  wire(g, 2, 4);

  // лампочка на сети a: показывает, как волна бежит по кольцу
  rect(g, 7, 5, BULB, 2, 2); // BULB x7-8 y5-6, N=(7,4),(8,4) — сеть a

  return g;
}
